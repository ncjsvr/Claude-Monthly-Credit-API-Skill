#!/usr/bin/env node
/**
 * delegate.mjs
 *
 * Hands a self-contained coding task to a Claude Agent SDK worker billed to
 * Claude Console API credit instead of Claude Code plan limits.
 *
 * Typical use from Claude Code's Bash tool (Git Bash on Windows):
 *
 *   node ~/.claude/delegate/delegate.mjs --cwd "$PWD" --task-file - <<'BRIEF'
 *   ...full task brief...
 *   BRIEF
 *
 * The first line of output is always one of:
 *   DELEGATE_OK          finished; report and changed files follow
 *   DELEGATE_PARTIAL     stopped at the budget or turn cap
 *   DELEGATE_FAILED      something went wrong; details follow
 *   DELEGATE_UNAVAILABLE credit used up or key not usable; do the task yourself
 */

import { query } from "@anthropic-ai/claude-agent-sdk";
import { appendFileSync, existsSync, mkdirSync, readFileSync, statSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { execFileSync } from "node:child_process";

const HERE = dirname(fileURLToPath(import.meta.url));
const KEY_FILE = process.env.DELEGATE_KEY_FILE || join(HERE, "api-key.txt");
const LOG_DIR = join(HERE, "logs");

const DEFAULTS = { model: "sonnet", budget: 3, maxTurns: 80 };
const MAX_BUDGET = 20;
const EXIT = { OK: 0, FAILED: 1, USAGE: 2, UNAVAILABLE: 3 };

// Signals that the credit can't be used right now, so the caller should do the work itself.
const UNAVAILABLE_ERRORS = new Set([
  "billing_error",
  "authentication_failed",
  "account_on_hold",
  "oauth_org_not_allowed",
  "verification_required",
]);
const UNAVAILABLE_TEXT = /credit balance (is )?too low|credits_required|invalid x-api-key|invalid api key|authentication_error/i;

// Variables inherited from the parent Claude Code session that must not leak into the worker:
// its auth would override the API key, and its session markers would make the worker look
// like a nested Claude Code session rather than an Agent SDK app.
const STRIP_ENV = [
  "ANTHROPIC_API_KEY",
  "ANTHROPIC_AUTH_TOKEN",
  "CLAUDE_CODE_OAUTH_TOKEN",
  "CLAUDECODE",
  "CLAUDE_CODE_ENTRYPOINT",
  "CLAUDE_CODE_SSE_PORT",
];

const EDIT_TOOLS = ["Read", "Glob", "Grep", "Edit", "Write", "NotebookEdit", "Bash"];
const WRITE_TOOLS = ["Edit", "Write", "NotebookEdit"];
const READ_TOOLS = [
  "Read",
  "Glob",
  "Grep",
  "Bash(git log *)",
  "Bash(git diff *)",
  "Bash(git show *)",
  "Bash(git status *)",
  "Bash(git blame *)",
  "Bash(ls *)",
];
const GIT_DENY = [
  "Bash(git commit *)",
  "Bash(git push *)",
  "Bash(git reset *)",
  "Bash(git checkout *)",
  "Bash(git switch *)",
  "Bash(git restore *)",
  "Bash(git stash *)",
  "Bash(git clean *)",
  "Bash(git rebase *)",
  "Bash(git merge *)",
  "Bash(git branch *)",
];

const WORKER_RULES = `
You are a delegated worker running unattended. Another Claude Code session wrote the brief below and will review your changes when you finish. Nobody can answer questions mid-task.

Rules:
- Stay inside the working directory.
- Complete the task fully. If something is ambiguous, choose the option most consistent with the existing code and record the choice under NOTES.
- Follow CLAUDE.md and the conventions already in the codebase.
- Do not commit, push, create or switch branches, stash, reset, rebase, or discard changes. Leave every change uncommitted for review.
- Never add "Generated by Claude", "Generated with Claude Code", Co-Authored-By trailers or any other AI attribution to code, comments, file headers, docs or messages.
- Do not touch secrets, .env files, credentials or deployment configuration unless the brief explicitly asks.
- Where the project has relevant tests, a type check, lint or a build, run them and fix failures your change caused.
- If a tool call is denied, work around it or note it; do not retry the same call.

Finish with this report and nothing after it (25 lines max):
STATUS: done | partial | blocked
CHANGED:
- path/to/file (what changed, a few words)
CHECKS: what you ran and the result, or "none available"
NOTES: decisions, assumptions, anything unfinished or that the reviewer should check
`.trim();

const READ_ONLY_RULES = `
You are a delegated research worker running unattended. Another Claude Code session wrote the brief below and will use your findings. Nobody can answer questions mid-task.

Rules:
- Do not create, modify or delete any files.
- Be specific: cite file paths and line numbers; quote short snippets only where they matter.
- If something can't be determined from the code, say so rather than guessing.

Finish with this report and nothing after it (40 lines max):
STATUS: done | partial | blocked
FINDINGS: the answer, with file:line references
NOTES: caveats, open questions, suggested next steps
`.trim();

const USAGE = `Usage: node delegate.mjs [options]
  --cwd <dir>          Project directory to work in (default: current directory)
  --task <text>        Task brief as a single argument
  --task-file <path>   Read the brief from a file; use "-" to read it from stdin (heredoc)
  --read-only          Investigate and report only; no file changes
  --model <name>       Model alias or ID (default: ${DEFAULTS.model})
  --budget <usd>       Spend cap for this run in USD (default: ${DEFAULTS.budget}, max ${MAX_BUDGET})
  --max-turns <n>      Turn cap (default: ${DEFAULTS.maxTurns})
  --check              Make a tiny test call to confirm the key and credit work`;

// Auto-approving tools via allowedTools is intentional; drop the SDK's warning about it.
process.removeAllListeners("warning");
process.on("warning", (w) => {
  if (w.code !== "CLAUDE_SDK_CAN_USE_TOOL_SHADOWED") process.stderr.write(`${w.name}: ${w.message}\n`);
});

class Finished extends Error {}

function finish(code, lines) {
  const text = lines.filter((l) => l !== null && l !== undefined).join("\n") + "\n";
  process.exitCode = code;
  process.stdout.write(text, () => process.exit(code));
  throw new Finished();
}

const usageError = (msg) => finish(EXIT.USAGE, [`DELEGATE_FAILED: ${msg}`, "", USAGE]);

const unavailable = (reason, extra = []) =>
  finish(EXIT.UNAVAILABLE, [`DELEGATE_UNAVAILABLE: ${reason}`, ...extra, "Do this task yourself in the main session."]);

function parseArgs(argv) {
  const opts = { cwd: process.cwd(), readOnly: false, check: false, ...DEFAULTS };
  for (let i = 0; i < argv.length; i++) {
    const arg = argv[i];
    const value = () => {
      if (i + 1 >= argv.length) usageError(`missing value for ${arg}`);
      return argv[++i];
    };
    switch (arg) {
      case "--cwd": opts.cwd = value(); break;
      case "--task": opts.task = value(); break;
      case "--task-file": opts.taskFile = value(); break;
      case "--model": opts.model = value(); break;
      case "--budget": opts.budget = Number(value()); break;
      case "--max-turns": opts.maxTurns = Number(value()); break;
      case "--read-only": opts.readOnly = true; break;
      case "--check": opts.check = true; break;
      case "-h":
      case "--help": finish(EXIT.OK, [USAGE]); break;
      default: usageError(`unknown argument: ${arg}`);
    }
  }
  if (!(opts.budget > 0 && opts.budget <= MAX_BUDGET)) usageError(`--budget must be above 0 and at most ${MAX_BUDGET}`);
  if (!(Number.isInteger(opts.maxTurns) && opts.maxTurns > 0)) usageError("--max-turns must be a positive whole number");
  return opts;
}

// Git Bash can hand Node paths like /c/Users/...; Node on Windows needs C:/Users/...
function toNativePath(p) {
  if (process.platform !== "win32") return p;
  const m = /^\/([a-zA-Z])(?:\/(.*))?$/.exec(p);
  return m ? `${m[1].toUpperCase()}:/${m[2] ?? ""}` : p;
}

async function readBrief(opts) {
  if (opts.task) return opts.task;
  if (opts.taskFile === "-") {
    const chunks = [];
    for await (const chunk of process.stdin) chunks.push(chunk);
    return Buffer.concat(chunks).toString("utf8");
  }
  if (opts.taskFile) {
    const p = toNativePath(opts.taskFile);
    if (!existsSync(p)) usageError(`brief file not found: ${p}`);
    return readFileSync(p, "utf8");
  }
  return usageError("no task given (use --task, --task-file <path>, or --task-file - with a heredoc)");
}

function loadKey() {
  if (!existsSync(KEY_FILE)) unavailable(`no API key file at ${KEY_FILE} (run install.ps1 to set it up).`);
  const key = readFileSync(KEY_FILE, "utf8").trim();
  if (!key.startsWith("sk-ant-")) unavailable(`${KEY_FILE} doesn't contain an Anthropic API key.`);
  return key;
}

function workerEnv(key) {
  const env = { ...process.env };
  for (const name of STRIP_ENV) delete env[name];
  env.ANTHROPIC_API_KEY = key;
  env.DELEGATE_WORKER = "1";
  env.CLAUDE_AGENT_SDK_CLIENT_APP = "delegate-kit/1.0";
  return env;
}

function gitStatus(cwd) {
  try {
    const out = execFileSync("git", ["-C", cwd, "status", "--short", "--untracked-files=all"], {
      encoding: "utf8",
      stdio: ["ignore", "pipe", "ignore"],
    }).trimEnd();
    if (!out) return ["(none)"];
    const lines = out.split(/\r?\n/);
    return lines.length > 40 ? [...lines.slice(0, 40), `... and ${lines.length - 40} more`] : lines;
  } catch {
    return ["(not a git repository)"];
  }
}

function tail(text, n) {
  const lines = text.trim().split(/\r?\n/);
  return lines.slice(-n).join("\n");
}

function makeLogger(label) {
  mkdirSync(LOG_DIR, { recursive: true });
  const stamp = new Date().toISOString().replace(/[:.]/g, "-");
  const firstLine = label.split(/\r?\n/).find((l) => l.trim()) || "task";
  const slug = firstLine.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-+|-+$/g, "").slice(0, 40) || "task";
  const file = join(LOG_DIR, `${stamp}-${slug}.jsonl`);
  const write = (obj) => {
    try {
      appendFileSync(file, JSON.stringify(obj) + "\n");
    } catch {
      // logging must never break a run
    }
  };
  return { file, write };
}

async function main() {
  const opts = parseArgs(process.argv.slice(2));

  if (process.env.DELEGATE_WORKER === "1") {
    unavailable("nested delegation is disabled inside a delegate worker.");
  }

  const key = loadKey();
  const cwd = opts.check ? HERE : resolve(toNativePath(opts.cwd));
  if (!existsSync(cwd) || !statSync(cwd).isDirectory()) usageError(`working directory not found: ${cwd}`);

  const brief = opts.check ? "Reply with exactly the word OK. Do not use any tools." : (await readBrief(opts)).trim();
  if (!brief) usageError("the task brief is empty");

  const readOnly = opts.readOnly || opts.check;
  const log = makeLogger(opts.check ? "check" : brief);
  log.write({ type: "delegate_start", cwd, model: opts.model, budget: opts.budget, maxTurns: opts.maxTurns, readOnly, brief });

  const options = {
    cwd,
    model: opts.model,
    maxTurns: opts.check ? 2 : opts.maxTurns,
    maxBudgetUsd: opts.check ? 0.25 : opts.budget,
    env: workerEnv(key),
    // Project settings and CLAUDE.md only. User-level settings (including the global
    // delegation rule and the delegate skill) stay out so the worker never tries to delegate.
    settingSources: opts.check ? [] : ["project", "local"],
    settings: { attribution: { commit: "", pr: "", sessionUrl: false } },
    systemPrompt: { type: "preset", preset: "claude_code", append: readOnly ? READ_ONLY_RULES : WORKER_RULES },
    permissionMode: readOnly ? "default" : "acceptEdits",
    allowedTools: readOnly ? READ_TOOLS : EDIT_TOOLS,
    disallowedTools: readOnly ? [...WRITE_TOOLS, ...GIT_DENY] : GIT_DENY,
    // Anything that would normally prompt for approval is refused: nobody is there to answer.
    canUseTool: async (toolName) => ({
      behavior: "deny",
      message: `${toolName} needs interactive approval, which an unattended delegate doesn't have. Work around it or list it under NOTES.`,
    }),
    persistSession: false,
  };

  let result = null;
  let lastText = "";
  const problems = [];
  const started = Date.now();

  try {
    for await (const msg of query({ prompt: brief, options })) {
      log.write(msg);
      if (msg.type === "assistant") {
        if (msg.error) problems.push(msg.error);
        if (!msg.parent_tool_use_id) {
          const text = (msg.message?.content ?? [])
            .filter((block) => block.type === "text")
            .map((block) => block.text)
            .join("\n")
            .trim();
          if (text) lastText = text;
        }
      } else if (msg.type === "result") {
        result = msg;
        if (Array.isArray(msg.errors)) problems.push(...msg.errors);
      }
    }
  } catch (err) {
    // The SDK raises after a cap result in single-shot mode; the result is already captured.
    problems.push(String(err?.message ?? err));
    log.write({ type: "delegate_exception", message: String(err?.stack ?? err) });
  }

  const cost = typeof result?.total_cost_usd === "number" ? result.total_cost_usd : 0;
  const seconds = Math.round((Date.now() - started) / 1000);
  const meta = `~$${cost.toFixed(2)} API credit, ${result?.num_turns ?? "?"} turns, ${seconds}s, model ${opts.model}`;
  const changes = readOnly ? [] : ["", "Uncommitted changes in the working tree now:", ...gitStatus(cwd)];
  const logLine = `Log: ${log.file}`;

  if (result?.subtype === "success" && !result.is_error) {
    const report = (result.result || lastText || "(no report)").trim();
    finish(EXIT.OK, [`DELEGATE_OK (${meta})`, "", report, ...changes, "", logLine]);
  }

  const allText = [...problems, result?.result ?? "", lastText].join("\n");
  if (problems.some((p) => UNAVAILABLE_ERRORS.has(p)) || UNAVAILABLE_TEXT.test(allText)) {
    unavailable("the API credit is used up, or this key/org can't be used for delegate runs.", [`(${meta})`, logLine]);
  }

  if (result?.subtype === "error_max_budget_usd" || result?.subtype === "error_max_turns") {
    const cap = result.subtype === "error_max_budget_usd" ? `the $${opts.budget} budget cap` : `the ${opts.maxTurns}-turn cap`;
    finish(EXIT.FAILED, [
      `DELEGATE_PARTIAL: stopped at ${cap} (${meta})`,
      lastText ? `\nLast message from the worker:\n${tail(lastText, 15)}` : null,
      ...changes,
      "",
      "Review what was done, then finish it yourself or re-delegate the remainder with a larger --budget.",
      logLine,
    ]);
  }

  const detail = [...new Set(problems)].slice(-5).join(" | ") || result?.subtype || "no result received";
  finish(EXIT.FAILED, [
    `DELEGATE_FAILED: ${detail} (${meta})`,
    lastText ? `\nLast message from the worker:\n${tail(lastText, 15)}` : null,
    ...changes,
    "",
    logLine,
  ]);
}

main().catch((err) => {
  if (err instanceof Finished) return;
  process.exitCode = EXIT.FAILED;
  process.stdout.write(`DELEGATE_FAILED: ${err?.message ?? err}\n`, () => process.exit(EXIT.FAILED));
});
